"""Writes styles/horizon.shader.toml (its colour params are repetitive)."""
import os

COLS = {
    "sky_top": (0.05, 0.02, 0.16, "Sky colour overhead"),
    "sky_low": (0.55, 0.10, 0.45, "Sky colour just above the horizon"),
    "glow": (1.00, 0.35, 0.60, "The band of light lying on the horizon"),
    "sun_hi": (1.00, 0.86, 0.25, "Top of the sun"),
    "sun_lo": (1.00, 0.16, 0.50, "Bottom of the sun"),
    "ground": (0.02, 0.01, 0.05, "What lies under the horizon, past the last road tile"),
}
NUMS = [
    ("sun_x", 0.0, -3.2, 3.2, "Sun azimuth (rad), 0 = straight down the road"),
    ("sun_y", 0.10, -0.5, 1.2, "Sun centre elevation (rad)"),
    ("sun_size", 0.21, 0.01, 0.8, "Sun angular radius (rad)"),
    ("sun_gain", 2.4, 0.0, 12.0, "Sun radiance; past 1 it blooms"),
    ("stripes", 1.0, 0.0, 1.0, "How much the lower sun is cut into bands"),
    ("stripe_phase", 0.0, 0.0, 100000.0, "Scrolls the bands downward"),
    ("rings", 0.0, 0.0, 1.0, "Sun drawn as concentric colour rings instead of a gradient"),
    ("stars", 0.8, 0.0, 2.0, "Star brightness"),
    ("glow_gain", 1.3, 0.0, 8.0, "Horizon band radiance"),
    ("haze", 0.07, 0.01, 0.6, "Horizon band height (rad)"),
    ("halo", 1.0, 0.0, 6.0, "The soft bed of light round the sun; the music's kick swells it"),
    ("echo", 0.0, 0.0, 2.0, "Rings of light leaving the sun on the beat: their strength"),
    ("echo_phase", 0.0, 0.0, 1.0, "Where in the beat the music is: how far the newest ring has travelled"),
]

HEAD = """# The whole sky of Kandinski, painted where nothing was drawn: a vertical
# gradient, hashed stars, a band of light on the horizon and the striped sun.
# It is an hdr style that feeds bloom, so the sun and the horizon line glow
# by themselves. Every colour and number is a param that scripts/drive.rhai
# cross-fades between stages with set_post_style_param.
# Generated by tools/gen_horizon_toml.py.
version = 1
name = "horizon"
label = "Horizon (sky + sun)"
stage = "hdr"
shader = "horizon.wgsl"
inputs = ["depth"]
feeds_bloom = true
"""

out = [HEAD]
for k, (r, g, b, h) in COLS.items():
    for ch, v in zip("rgb", (r, g, b)):
        s = f"[params.{k}_{ch}]\ndefault = {v}\nmin = 0.0\nmax = 1.0\n"
        if ch == "r":
            s += f'help = "{h}"\n'
        out.append(s)
for k, d, lo, hi, h in NUMS:
    out.append(f'[params.{k}]\ndefault = {d}\nmin = {lo}\nmax = {hi}\nhelp = "{h}"\n')
path = os.path.join(os.path.dirname(__file__), "..", "styles", "horizon.shader.toml")
open(path, "w", newline="\n").write("\n".join(out))
print(os.path.normpath(path))

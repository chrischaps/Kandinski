"""Writes scenes/kandinski.scene.toml (and its capture variants).

Everything that moves in Kandinski is a pooled entity that scripts/drive.rhai
re-places every frame, so the scene is mostly repetition. This script is the
one place pool sizes live: scripts read them back from the `pools` table in
scripts/lib/pools.rhai, which this script also writes.

    python tools/build_scene.py
"""
import os

ROOT = os.path.normpath(os.path.join(os.path.dirname(__file__), ".."))

N_TILES = 64                 # road tiles (8 m each): must be even (a/b alternate)
# Scenery drawn in glyphs (Flint's per-entity ASCII style). Off: the models'
# own dark faces and neon trim lines show. Flip and rebuild to compare.
ASCII = False

POOLS = {                    # name -> (model asset, count, ascii?)
    "palm": ("palm", 34, True),
    "pine": ("pine", 34, True),
    "lamp": ("lamp", 14, False),
    "sign": ("sign", 4, False),
    "tower_a": ("tower_a", 12, True),
    "tower_b": ("tower_b", 12, True),
    "tower_c": ("tower_c", 12, True),
    "circle": ("shape_circle", 6, False),
    "triangle": ("shape_triangle", 6, False),
    "square": ("shape_square", 6, False),
    "gate": ("gate", 2, False),
}
N_TRAFFIC = 12               # the densest event uses them all; scripts/lib/tour.rhai says how many an event has
N_RIVAL = 5                  # race events: the hero body and four wheels each, painted by drive.rhai
N_MOUNT = 9                  # three each of mountain_a/b/c, in a ring behind the horizon

TRAFFIC_BODY = [
    (0.02, 0.10, 0.16), (0.14, 0.02, 0.10), (0.12, 0.09, 0.01), (0.02, 0.12, 0.06),
    (0.10, 0.10, 0.12), (0.05, 0.02, 0.14), (0.14, 0.05, 0.01), (0.01, 0.07, 0.14),
]


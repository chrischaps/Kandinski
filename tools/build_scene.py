"""Writes scenes/kandinski.scene.toml (and its capture variants).

Everything that moves in Kandinski is a pooled entity that scripts/drive.rhai
re-places every frame, so the scene is mostly repetition. This script is the
one place pool sizes live: scripts read them back from the `pools` table in
scripts/lib/pools.rhai, which this script also writes.

    python tools/build_scene.py
"""
import os

ROOT = os.path.normpath(os.path.join(os.path.dirname(__file__), ".."))

N_TILES = 64                 # road tiles (8 m each): must be even (a/b alternate)
POOLS = {                    # name -> (model asset, count, ascii?)
    "palm": ("palm", 34, True),
    "pine": ("pine", 34, True),
    "lamp": ("lamp", 14, False),
    "sign": ("sign", 4, False),
    "tower_a": ("tower_a", 12, True),
    "tower_b": ("tower_b", 12, True),
    "tower_c": ("tower_c", 12, True),
    "circle": ("shape_circle", 6, False),
    "triangle": ("shape_triangle", 6, False),
    "square": ("shape_square", 6, False),
    "gate": ("gate", 2, False),
}
N_TRAFFIC = 8
N_MOUNT = 9                  # three each of mountain_a/b/c, in a ring behind the horizon

TRAFFIC_BODY = [
    (0.02, 0.10, 0.16), (0.14, 0.02, 0.10), (0.12, 0.09, 0.01), (0.02, 0.12, 0.06),
    (0.10, 0.10, 0.12), (0.05, 0.02, 0.14), (0.14, 0.05, 0.01), (0.01, 0.07, 0.14),
]

HEADER = '''# ================================================================
#  KANDINSKI  -  point and line to horizon
# ================================================================
#  GENERATED by tools/build_scene.py: edit that, not this.
#
#  A high-speed drive through five stages, in the line of Rad Racer
#  and OutRun. The world is a treadmill: the car stays at the origin
#  and scripts/drive.rhai re-places {n_tiles} road tiles and the pooled
#  scenery under it every frame, shearing tiles sideways for curves
#  and pitching them for hills.
#
#    play.bat
#
#  W / Up      accelerate          A D / Left Right   steer
#  S / Down    brake               Enter / Space      start
#  P           pause               R                  back to the title
#  Gamepad: stick steers, RT / A accelerates, LT / X brakes, Start starts
# ================================================================

[scene]
name = "Kandinski"
version = "1.0"
description = "Point and line to horizon: a retro high-speed drive"
input_config = "config/input.toml"

[camera]
position = [0.0, 2.3, 7.4]
target = [0.0, 1.1, -30.0]
fov = 62.0
near = 0.3
far = 4000.0

# The world is unlit: a flat ambient of 3 and no sun, so a material's colour
# is its radiance. Colour 1 is radiance 3, which blooms; the road is ~0.005.
[environment]
ambient_sky = [3.0, 3.0, 3.0]
ambient_ground = [3.0, 3.0, 3.0]

[post_process]
bloom_enabled = true
bloom_intensity = 0.22
bloom_threshold = 1.0
exposure = 1.0
fog_enabled = true
fog_color = [0.30, 0.03, 0.16]
fog_density = 0.0030
fog_start = 60.0

# The sky and the sun (styles/horizon.*). drive.rhai owns every value.
[post_process.styles.horizon]

# Scenery is drawn in glyphs; the table is only the preset for those entities.
[post_process.styles.ascii]
scope = "entities"
cell = 6
color = "source"
ground = "black"
edges = 1.0
edge_ink = "hue"
glow = 0.5
ink = 1.3
exposure = 1.0
outline = 1.0
smoothing = 0.2

# Glow that crosses glyph cells, so the glyph scenery reads as lit tubes.
[post_process.styles.display_bloom]
intensity = 0.9
threshold = 0.62
levels = 5

# The glass (styles/crt.*).
[post_process.styles.crt]

[entities.sun]
[entities.sun.light]
type = "directional"
direction = [0.0, 1.0, 0.0]
color = [1.0, 1.0, 1.0]
intensity = 0.0

# ── Game ────────────────────────────────────────────────────────
[entities.game]
[entities.game.game_state]
autopilot = {autopilot}
start_stage = {start_stage}
start_speed = {start_speed}
[entities.game.script]
source = "drive.rhai"

[entities.hud]
[entities.hud.script]
source = "hud.rhai"

[entities.audio]
[entities.audio.script]
source = "audio.rhai"
'''

LOOPS = [("snd_engine_low", "engine_low", "sfx"), ("snd_engine_high", "engine_high", "sfx"),
         ("snd_wind", "wind", "sfx"), ("snd_skid", "skid", "sfx"), ("snd_offroad", "offroad", "sfx"),
         ("snd_music_drive", "music_drive", "music"), ("snd_music_title", "music_title", "music")]


def build(autopilot=False, start_stage=0, start_speed=0.0):
    o = [HEADER.format(n_tiles=N_TILES, autopilot=str(autopilot).lower(),
                       start_stage=start_stage, start_speed=float(start_speed))]
    o.append("# ── Audio loops: autoplay at volume 0, scripts/audio.rhai fades them ──")
    for ent, f, bus in LOOPS:
        o.append(f'[entities.{ent}]\n[entities.{ent}.audio_source]\nfile = "audio/{f}.ogg"\nloop = true\n'
                 f'autoplay = true\nspatial = false\nvolume = 0.0\nbus = "{bus}"\n')

    o.append("# ── The car ──")
    o.append('[entities.car]\n[entities.car.transform]\nposition = [0, 0, 0]\n[entities.car.model]\nasset = "car_player"\n')

    o.append("# ── Road tiles: seg_i shears, tile_i (its child) pitches ──")
    for i in range(N_TILES):
        v = "a" if i % 2 == 0 else "b"
        o.append(f'[entities.seg_{i}]\n[entities.seg_{i}.transform]\nposition = [0, -1000, 0]\n'
                 f'[entities.tile_{i}]\nparent = "seg_{i}"\n[entities.tile_{i}.transform]\nposition = [0, 0, 0]\n'
                 f'[entities.tile_{i}.model]\nasset = "tile_{v}"\n')

    o.append("# ── Traffic ──")
    for i in range(N_TRAFFIC):
        asset = "car_traffic_b" if i % 4 == 3 else "car_traffic_a"
        r, g, b = TRAFFIC_BODY[i % len(TRAFFIC_BODY)]
        r, g, b = round(r * 0.3, 4), round(g * 0.3, 4), round(b * 0.3, 4)   # x3 ambient: keep paint dark
        o.append(f'[entities.traffic_{i}]\n[entities.traffic_{i}.transform]\nposition = [0, -1000, 0]\n'
                 f'[entities.traffic_{i}.model]\nasset = "{asset}"\n'
                 f'[entities.traffic_{i}.material_overrides]\nbody = [{r}, {g}, {b}]\n')

    o.append("# ── Scenery pools ──")
    for name, (asset, count, ascii_) in POOLS.items():
        for i in range(count):
            s = (f'[entities.{name}_{i}]\n[entities.{name}_{i}.transform]\nposition = [0, -1000, 0]\n'
                 f'[entities.{name}_{i}.model]\nasset = "{asset}"\n')
            if ascii_ and name.startswith("tower"):
                # the city is one ink: lit windows as bright glyphs, walls a faint weave
                s += (f'[entities.{name}_{i}.ascii_style]\ncolor = "tint"\ntint = [0.42, 0.62, 1.0]\n'
                      f'exposure = 0.0\nbrightness = -0.06\n')
            elif ascii_:
                s += f'[entities.{name}_{i}.style_mask]\nstyle = "ascii"\n'
            o.append(s)

    o.append("# ── Mountains: a ring far behind everything, scrolled by the road's heading ──")
    for i in range(N_MOUNT):
        asset = "mountain_" + "abc"[i % 3]
        o.append(f'[entities.mount_{i}]\n[entities.mount_{i}.transform]\nposition = [0, -1000, 0]\n'
                 f'[entities.mount_{i}.model]\nasset = "{asset}"\n'
                 f'[entities.mount_{i}.style_mask]\nstyle = "ascii"\n')
    return "\n".join(o)


def write_pools():
    lines = ["// GENERATED by tools/build_scene.py: pool sizes the scene was built with.",
             f"export const N_TILES = {N_TILES};", f"export const N_TRAFFIC = {N_TRAFFIC};",
             f"export const N_MOUNT = {N_MOUNT};", "", "fn pools() {", "    #{"]
    for name, (_, count, _) in POOLS.items():
        lines.append(f"        {name}: {count},")
    lines += ["    }", "}", ""]
    with open(os.path.join(ROOT, "scripts", "lib", "pools.rhai"), "w", newline="\n") as f:
        f.write("\n".join(lines))


if __name__ == "__main__":
    variants = {
        "kandinski": dict(),
        # captures and tests: the game drives itself from the first frame
        "auto_s0": dict(autopilot=True, start_stage=0, start_speed=70.0),
        "auto_s1": dict(autopilot=True, start_stage=1, start_speed=70.0),
        "auto_s2": dict(autopilot=True, start_stage=2, start_speed=70.0),
        "auto_s3": dict(autopilot=True, start_stage=3, start_speed=70.0),
        "auto_s4": dict(autopilot=True, start_stage=4, start_speed=70.0),
    }
    for name, kw in variants.items():
        p = os.path.join(ROOT, "scenes", f"{name}.scene.toml")
        with open(p, "w", newline="\n", encoding="utf-8") as f:
            f.write(build(**kw))
        print(p)
    write_pools()

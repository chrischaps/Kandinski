LOOPS = [("snd_engine_low", "engine_low", "sfx"), ("snd_engine_high", "engine_high", "sfx"),
         ("snd_wind", "wind", "sfx"), ("snd_skid", "skid", "sfx"), ("snd_offroad", "offroad", "sfx"),
         ("snd_music_drive", "music_drive", "music"), ("snd_music_title", "music_title", "music")]


# The player's car: a root the script places and yaws, a body that rolls,
# pitches and heaves on its springs, and four wheels that stay on the road.
# Hubs (x, y, z); left wheels are the same model yawed 180 degrees (the
# script does that: it owns every wheel rotation).
WHEELS = {
    "wheel_fl": (-0.80, 0.33, -1.32), "wheel_fr": (0.80, 0.33, -1.32),
    "wheel_rl": (-0.80, 0.33, 1.28), "wheel_rr": (0.80, 0.33, 1.28),
}


def wheel_asset():
    """models/car_wheel.glb is made by the car-model task; until it lands a
    plain placeholder (tools/build_scene.py writes it) stands in."""
    if os.path.exists(os.path.join(ROOT, "models", "car_wheel.glb")):
        return "car_wheel"
    path = os.path.join(ROOT, "models", "car_wheel_placeholder.glb")
    if not os.path.exists(path):
        import math
        import sys
        sys.path.insert(0, os.path.dirname(__file__))
        from glb import Model
        m = Model()
        r, w, n = 0.33, 0.28, 12
        ring = [(math.cos(2 * math.pi * i / n) * r, math.sin(2 * math.pi * i / n) * r) for i in range(n)]
        for i in range(n):
            (za, ya), (zb, yb) = ring[i], ring[(i + 1) % n]
            m.quad("tyre", [(-w / 2, ya, za), (w / 2, ya, za), (w / 2, yb, zb), (-w / 2, yb, zb)])
            m.tri("tyre", (w / 2, 0, 0), (w / 2, yb, zb), (w / 2, ya, za))
            m.tri("tyre", (-w / 2, 0, 0), (-w / 2, ya, za), (-w / 2, yb, zb))
        # one bright spoke on the outer face, so spin reads
        m.quad("rim", [(w / 2 + 0.004, -0.03, 0.0), (w / 2 + 0.004, -0.03, r * 0.8),
                       (w / 2 + 0.004, 0.03, r * 0.8), (w / 2 + 0.004, 0.03, 0.0)])
        m.material("tyre", (0.004, 0.004, 0.006))
        m.material("rim", (0.6, 0.6, 0.7))
        m.save(path)
    return "car_wheel_placeholder"


def build(autopilot=False, start_stage=0, start_speed=0.0, manual=False, telemetry=False,
          test_track=False, test_curve=0.0, traffic=True, start_boost=0.0, ap_skill=1.0,
          script="drive.rhai", telemetry_hz=10.0, test_wide=False, cruise=0.0,
          start_event=-1, ap_style=0, no_clock=False, persist=None, ap_assist=False, ghost_rivals=False):
    """Scene text. Keywords are game_state fields (schemas/components/game_state.toml).
    `start_event` 0-14 starts in that GRAND TOUR event (100 = HORIZON): with the
    autopilot and no start_speed it plays by the rules to the results screen.
    `persist` defaults to off for anything but the game itself, so tests leave
    the player's save alone."""
    if persist is None:
        persist = not (autopilot or manual or telemetry or start_event >= 0)
    b = lambda v: str(v).lower()
    o = [HEADER.format(n_tiles=N_TILES, autopilot=b(autopilot), start_stage=start_stage,
                       start_speed=float(start_speed), manual=b(manual), telemetry=b(telemetry),
                       test_track=b(test_track), test_curve=float(test_curve), traffic=b(traffic),
                       start_boost=float(start_boost), ap_skill=float(ap_skill), script=script,
                       telemetry_hz=float(telemetry_hz), test_wide=b(test_wide), cruise=float(cruise),
                       start_event=int(start_event), ap_style=int(ap_style), no_clock=b(no_clock),
                       persist=b(persist), ap_assist=b(ap_assist), ghost_rivals=b(ghost_rivals))]
    o.append("# ── Audio loops: autoplay at volume 0, scripts/audio.rhai fades them ──")
    for ent, f, bus in LOOPS:
        o.append(f'[entities.{ent}]\n[entities.{ent}.audio_source]\nfile = "audio/{f}.ogg"\nloop = true\n'
                 f'autoplay = true\nspatial = false\nvolume = 0.0\nbus = "{bus}"\n')

    o.append("# ── The car ──")
    o.append('[entities.car]\n[entities.car.transform]\nposition = [0, 0, 0]\n')
    o.append('[entities.car_body]\nparent = "car"\n[entities.car_body.transform]\nposition = [0, 0, 0]\n'
             '[entities.car_body.model]\nasset = "car_player"\n')
    wa = wheel_asset()
    for name, (x, y, z) in WHEELS.items():
        o.append(f'[entities.{name}]\nparent = "car"\n[entities.{name}.transform]\nposition = [{x}, {y}, {z}]\n'
                 f'[entities.{name}.model]\nasset = "{wa}"\n')

    o.append("# ── Road tiles: seg_i shears, tile_i (its child) pitches ──")
    for i in range(N_TILES):
        v = "a" if i % 2 == 0 else "b"
        o.append(f'[entities.seg_{i}]\n[entities.seg_{i}.transform]\nposition = [0, -1000, 0]\n'
                 f'[entities.tile_{i}]\nparent = "seg_{i}"\n[entities.tile_{i}.transform]\nposition = [0, 0, 0]\n'
                 f'[entities.tile_{i}.model]\nasset = "tile_{v}"\n')

    o.append("# ── Traffic ──")
    for i in range(N_TRAFFIC):
        asset = "car_traffic_b" if i % 4 == 3 else "car_traffic_a"
        r, g, b = TRAFFIC_BODY[i % len(TRAFFIC_BODY)]
        r, g, b = round(r * 0.3, 4), round(g * 0.3, 4), round(b * 0.3, 4)   # x3 ambient: keep paint dark
        o.append(f'[entities.traffic_{i}]\n[entities.traffic_{i}.transform]\nposition = [0, -1000, 0]\n'
                 f'[entities.traffic_{i}.model]\nasset = "{asset}"\n'
                 f'[entities.traffic_{i}.material_overrides]\nbody = [{r}, {g}, {b}]\n')

    o.append("# ── Rivals (race events): a root the script places, the hero's body and wheels under it ──")
    for i in range(N_RIVAL):
        o.append(f'[entities.rival_{i}]\n[entities.rival_{i}.transform]\nposition = [0, -1000, 0]\n')
        o.append(f'[entities.rival_body_{i}]\nparent = "rival_{i}"\n[entities.rival_body_{i}.transform]\nposition = [0, 0, 0]\n'
                 f'[entities.rival_body_{i}.model]\nasset = "car_player"\n')
        for name, (x, y, z) in WHEELS.items():
            yaw = 180 if x < 0 else 0
            o.append(f'[entities.rival_{name}_{i}]\nparent = "rival_{i}"\n[entities.rival_{name}_{i}.transform]\n'
                     f'position = [{x}, {y}, {z}]\nrotation = [0, {yaw}, 0]\n'
                     f'[entities.rival_{name}_{i}.model]\nasset = "{wa}"\n')

    o.append("# ── Scenery pools ──")
    for name, (asset, count, ascii_) in POOLS.items():
        ascii_ = ascii_ and ASCII
        for i in range(count):
            s = (f'[entities.{name}_{i}]\n[entities.{name}_{i}.transform]\nposition = [0, -1000, 0]\n'
                 f'[entities.{name}_{i}.model]\nasset = "{asset}"\n')
            if ascii_ and name.startswith("tower"):
                # the city is one ink: lit windows as bright glyphs, walls a faint weave
                s += (f'[entities.{name}_{i}.ascii_style]\ncolor = "tint"\ntint = [0.42, 0.62, 1.0]\n'
                      f'exposure = 0.0\nbrightness = -0.06\n')
            elif ascii_:
                s += f'[entities.{name}_{i}.style_mask]\nstyle = "ascii"\n'
            o.append(s)

    o.append("# ── Mountains: a ring far behind everything, scrolled by the road's heading ──")
    for i in range(N_MOUNT):
        asset = "mountain_" + "abc"[i % 3]
        o.append(f'[entities.mount_{i}]\n[entities.mount_{i}.transform]\nposition = [0, -1000, 0]\n'
                 f'[entities.mount_{i}.model]\nasset = "{asset}"\n'
                 + (f'[entities.mount_{i}.style_mask]\nstyle = "ascii"\n' if ASCII else ''))
    return "\n".join(o)


def write_pools():
    lines = ["// GENERATED by tools/build_scene.py: pool sizes the scene was built with.",
             f"export const N_TILES = {N_TILES};", f"export const N_TRAFFIC = {N_TRAFFIC};",
             f"export const N_MOUNT = {N_MOUNT};", "", "fn pools() {", "    #{"]
    for name, (_, count, _) in POOLS.items():
        lines.append(f"        {name}: {count},")
    lines += ["    }", "}", ""]
    with open(os.path.join(ROOT, "scripts", "lib", "pools.rhai"), "w", newline="\n") as f:
        f.write("\n".join(lines))



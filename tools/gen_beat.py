"""Writes scripts/lib/beat.rhai: what the two music loops are doing, sixteenth
by sixteenth, so the world can move with them (drive.rhai's "pulse" block).

Nothing here is taken from the score. The shipped OGGs are decoded and
measured, so the table is what the player hears:

  kick    a low-band (35-110 Hz) onset at the start of a sixteenth: the kick
          drum, and at about half its strength the bass notes that land alone
  high    a 1.6-5 kHz onset at the start of a sixteenth: snare, hats and the
          arpeggio together (they cannot be told apart in the mix, so this is
          "how bright the sixteenth starts", not a snare)
  energy  the loudness of each bar, quietest bar 0, loudest 9

Each is a digit 0-9. The score (tools/gen_audio.py) is then used only as a
check: the kicks found are printed section by section beside the kicks the
drive track was written with.

    python tools/gen_beat.py            # write the table, print the check
    python tools/gen_beat.py --plot     # also snapshots/audio/beat_<track>.png
"""
import subprocess
import sys
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parent.parent
SR = 44100
# name -> (samples a beat, bars): tools/gen_audio.py's DRIVE_BEAT / TITLE_BEAT
TRACKS = {"drive": ("music_drive", 24500, 64), "title": ("music_title", 49000, 12)}


def decode(stem):
    p = ROOT / "audio" / f"{stem}.ogg"
    raw = subprocess.run(["ffmpeg", "-v", "error", "-i", str(p), "-f", "f32le", "-ac", "1", "-ar", str(SR), "-"],
                         capture_output=True, check=True).stdout
    return np.frombuffer(raw, dtype=np.float32).astype(float)


def band(x, lo, hi):
    X = np.fft.rfft(x)
    f = np.fft.rfftfreq(len(x), 1.0 / SR)
    X[(f < lo) | (f > hi)] = 0.0
    return np.fft.irfft(X, len(x))


def onsets(x, step, lo, hi, attack):
    """Per sixteenth: how much louder the band is in the `attack` seconds
    after the step starts than in the same span before it. The loop wraps."""
    env = np.abs(band(x, lo, hi))
    n = len(x) // step
    a = int(attack * SR)
    ext = np.concatenate([env[-a:], env])
    out = np.zeros(n)
    for i in range(n):
        s = i * step + a
        after = np.sqrt(np.mean(ext[s:s + a] ** 2))
        before = np.sqrt(np.mean(ext[s - a:s] ** 2))
        out[i] = max(after - before, 0.0)
    return out


def digits(v, top):
    return np.clip(np.round(9.0 * v / top), 0, 9).astype(int)


def measure(name):
    stem, beat, bars = TRACKS[name]
    x = decode(stem)
    step = beat // 4
    n = bars * 16
    assert len(x) == n * step, f"{stem}: {len(x)} samples, expected {n * step}"
    kick = onsets(x, step, 35.0, 110.0, 0.045)
    snare = onsets(x, step, 1600.0, 5000.0, 0.030)
    # a hit is judged against the track's own strong hits
    kd = digits(kick, np.percentile(kick, 97))
    sd = digits(snare, np.percentile(snare, 97))
    kd[kd < 3] = 0                                   # below a third of a full hit is bass movement, not a drum
    bar_db = np.array([20.0 * np.log10(np.sqrt(np.mean(x[b * 16 * step:(b + 1) * 16 * step] ** 2)) + 1e-9)
                       for b in range(bars)])
    ed = digits(bar_db - bar_db.min(), max(bar_db.max() - bar_db.min(), 1e-6))
    return dict(step=step / SR, kick=kd, high=sd, energy=ed, bar_db=bar_db, raw_kick=kick, raw_high=snare)


def check_drive(m):
    """The drive track's kicks as scored (gen_music_drive), against the kicks found."""
    def scored(b):
        s = ("intro" if b < 8 else "A" if b < 16 else "B" if b < 32 else "break" if b < 40 else "A2" if b < 56 else "turn")
        if s == "intro":
            return [] if b < 4 else [0]
        if s == "break":
            return [] if b < 36 else [0, 4, 8, 12]
        if s == "turn" and b >= 60:
            return [0, 8] if b < 63 else [0, 4, 8, 12]
        return [0, 4, 8, 12]
    hit = miss = extra = 0
    for b in range(64):
        want = set(scored(b))
        got = {st for st in range(16) if m["kick"][b * 16 + st] >= 3}
        hit += len(want & got); miss += len(want - got); extra += len(got - want)
    print(f"  drive kicks: {hit} of {hit + miss} scored kicks found, {extra} found that the score does not have")
    return miss, extra


def write(ms):
    o = ["// GENERATED by tools/gen_beat.py from the shipped OGGs: what each music loop",
         "// is doing, a digit (0-9) a sixteenth for kick (low onsets) and high (bright onsets), a digit a bar for",
         "// loudness. Call once and keep the map: a call builds the arrays again.", ""]
    for name, m in ms.items():
        o.append(f"fn {name}() {{")
        o.append("    #{")
        o.append(f"        step: {m['step']:.9f},        // seconds a sixteenth")
        o.append(f"        n: {len(m['kick'])},")
        for key in ("kick", "high", "energy"):
            rows = [", ".join(str(int(v)) for v in m[key][i:i + 32]) for i in range(0, len(m[key]), 32)]
            o.append(f"        {key}: [\n            " + ",\n            ".join(rows) + "\n        ],")
        o.append("    }")
        o.append("}")
        o.append("")
    (ROOT / "scripts" / "lib" / "beat.rhai").write_text("\n".join(o), encoding="utf-8", newline="\n")


def plot(ms):
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    for name, m in ms.items():
        bars = len(m["energy"])
        fig, ax = plt.subplots(3, 1, figsize=(16, 6), sharex=True)
        x = np.arange(len(m["kick"])) / 16.0
        ax[0].bar(x, m["kick"], width=1 / 16, color="#ff4fa8"); ax[0].set_ylabel("kick")
        ax[1].bar(x, m["high"], width=1 / 16, color="#49d6ff"); ax[1].set_ylabel("high")
        ax[2].step(np.arange(bars), m["energy"], where="post", color="#ffd84a"); ax[2].set_ylabel("bar loudness")
        ax[2].set_xlabel("bar")
        fig.suptitle(f"music_{name}: measured from the OGG")
        fig.tight_layout()
        out = ROOT / "snapshots" / "audio" / f"beat_{name}.png"
        out.parent.mkdir(parents=True, exist_ok=True)
        fig.savefig(out, dpi=90)
        print(" ", out)


if __name__ == "__main__":
    ms = {name: measure(name) for name in TRACKS}
    for name, m in ms.items():
        k = m["kick"]; s = m["high"]
        print(f"{name}: {len(k)} sixteenths of {m['step'] * 1000:.2f} ms, {int((k > 0).sum())} kicks, {int((s >= 5).sum())} bright sixteenths, "
              f"bars {m['bar_db'].min():.1f} to {m['bar_db'].max():.1f} dBFS")
        for b in range(0, len(m["energy"]), 4):
            print(f"  bar {b + 1:>2}  kick " + " ".join("".join(str(v) if v else "." for v in k[(b + i) * 16:(b + i + 1) * 16]) for i in range(4)))
    check_drive(ms["drive"])
    write(ms)
    if "--plot" in sys.argv:
        plot(ms)
